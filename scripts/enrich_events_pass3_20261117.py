def main():
    data = json.load(open(EV_PATH, encoding="utf-8"))
    ev = data["events"]
    changed = 0
    for e in ev:
        add = EXT.get(e["key"])
        if not add:
            continue
        bg_add, sig_add = add
        if bg_add and len(e.get("bg", "")) < 80:
            e["bg"] = (e.get("bg", "") + " " + bg_add).strip()
        if sig_add and len(e.get("significance", "")) < 70:
            e["significance"] = (e.get("significance", "") + " " + sig_add).strip()
        changed += 1
    shutil.copy2(EV_PATH, os.path.join(
        ROOT, "backups", f"events.json.bak-enrich3-{datetime.now():%Y%m%d-%H%M%S}"))
    json.dump(data, open(EV_PATH, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    print(f"[完成] 处理 {changed} 条")


if __name__ == "__main__":
    main()

def main():
    with open(EV_PATH, encoding="utf-8") as f:
        data = json.load(f)
    ev = data["events"]
    have = {e["key"] for e in ev}

    added, skipped = [], []
    for n in NEW:
        k = n["key"]
        if k in have:
            skipped.append(k)
            continue
        ev.append(n)
        have.add(k)
        added.append(k)

    ev.sort(key=lambda e: (e["year"], e["month"], e["day"]))
    data["events"] = ev

    os.makedirs(os.path.join(ROOT, "backups"), exist_ok=True)
    stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    bak = os.path.join(ROOT, "backups", f"events.json.bak-addevents-{stamp}")
    shutil.copy2(EV_PATH, bak)

    with open(EV_PATH, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print(f"[完成] 新增 {len(added)} 条，跳过重复 {len(skipped)} 条，总数 {len(ev)}")
    if skipped:
        print("  重复:", ", ".join(skipped))
    print("  备份:", bak)


if __name__ == "__main__":
    main()

def main():
    with open(EV_PATH, encoding="utf-8") as f:
        data = json.load(f)
    ev = data["events"]

    changed = 0
    for e in ev:
        k = e["key"]
        if k not in EXT:
            continue
        bg_add, sig_add, quotes_add = EXT[k]
        if bg_add:
            e["bg"] = (e.get("bg", "") + " " + bg_add).strip()
        if sig_add:
            e["significance"] = (e.get("significance", "") + " " + sig_add).strip()
        if quotes_add:
            qs = e.setdefault("quotes", [])
            for q in quotes_add:
                if q not in qs:
                    qs.append(q)
        if not e.get("furtherReading"):
            title = e["title"]
            e["furtherReading"] = [{
                "title": "共产党员网检索：" + title,
                "url": "https://search.12371.cn/search.php?t=newsmerge&client=no&q=" + quote(title),
            }]
        changed += 1

    os.makedirs(os.path.join(ROOT, "backups"), exist_ok=True)
    stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    bak = os.path.join(ROOT, "backups", f"events.json.bak-enrich-{stamp}")
    shutil.copy2(EV_PATH, bak)

    with open(EV_PATH, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print(f"[完成] 补齐 {changed} 条")
    print("  备份:", bak)


if __name__ == "__main__":
    main()

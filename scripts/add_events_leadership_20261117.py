def main():
    data = json.load(open(EV_PATH, encoding="utf-8"))
    ev = data["events"]
    have = {e["key"] for e in ev}
    added, skipped = [], []
    for n in NEW:
        if n["key"] in have:
            skipped.append(n["key"]); continue
        ev.append(n); have.add(n["key"]); added.append(n["key"])
    ev.sort(key=lambda e: (e["year"], e["month"], e["day"]))
    data["events"] = ev
    shutil.copy2(EV_PATH, os.path.join(
        ROOT, "backups", f"events.json.bak-leadership-{datetime.now():%Y%m%d-%H%M%S}"))
    json.dump(data, open(EV_PATH, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    print(f"[完成] 新增 {len(added)} 条，跳过 {len(skipped)} 条，总数 {len(ev)}")
    if skipped: print("  重复:", ", ".join(skipped))


if __name__ == "__main__":
    main()

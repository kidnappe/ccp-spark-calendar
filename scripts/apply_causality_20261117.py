def main():
    ca = json.load(open(CA_PATH, encoding="utf-8"))
    edges = ca["edges"]
    ev_keys = {e["key"] for e in json.load(open(EV_PATH, encoding="utf-8"))["events"]}

    bad = sorted({k for pair in DELETE for k in pair} - ev_keys)
    if bad:
        print("[错误] 删除边引用的 key 不存在于 events.json：", bad)
        raise SystemExit(1)

    # P2 事件尚未入库，相关边先记账跳过
    missing_add = [(f, t) for f, t, _, _ in ADD if f not in ev_keys or t not in ev_keys]
    ADD_OK = [(f, t, tier, ev) for f, t, tier, ev in ADD
              if f in ev_keys and t in ev_keys]

    before = len(edges)

    # 删除
    del_set = set(DELETE)
    removed = [e for e in edges if (e["from"], e["to"]) in del_set]
    edges = [e for e in edges if (e["from"], e["to"]) not in del_set]

    # 降级
    downgraded = 0
    for e in edges:
        if (e["from"], e["to"]) in DOWNGRADE and e.get("tier") != "background":
            e["tier"] = "background"
            e["evidence"] = (e.get("evidence", "") + "（补入中间节点后降为推断边）").strip()
            downgraded += 1

    # 新增
    existing = {(e["from"], e["to"]) for e in edges}
    added, skipped = 0, 0
    for f, t, tier, evidence in ADD_OK:
        if (f, t) in existing:
            skipped += 1
            continue
        edges.append({
            "from": f, "to": t, "tier": tier,
            "confidence": 0.9 if tier == "verified" else 0.6,
            "evidence": evidence,
            "source": "星火日历CAUSAL",
        })
        existing.add((f, t))
        added += 1

    shutil.copy2(CA_PATH, os.path.join(
        ROOT, "backups", f"causality.json.bak-20261117-{datetime.now():%H%M%S}"))

    ca["edges"] = edges
    json.dump(ca, open(CA_PATH, "w", encoding="utf-8"), ensure_ascii=False, indent=2)

    print(f"[完成] 边 {before} → {len(edges)}")
    print(f"  删除 {len(removed)} 条，降级 {downgraded} 条，新增 {added} 条，跳过已存在 {skipped} 条")
    if missing_add:
        print(f"  因 P2 事件未入库跳过 {len(missing_add)} 条：",
              ", ".join(f"{f}→{t}" for f, t in missing_add))


if __name__ == "__main__":
    main()
